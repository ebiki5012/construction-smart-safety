import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=name=>fs.readFileSync(new URL('../'+name,import.meta.url),'utf8');
const html=read('public/index.html'),css=read('public/workflow-v13.css'),workspace=read('public/workspace-v12.js'),server=read('server.js');
const modes=[...html.matchAll(/data-v12-mode="(write|lookup|compose|document)"/g)].map(m=>m[1]);
assert.deepEqual(modes,['write','lookup','compose','document'],'workflow tabs must follow real construction-site approval sequence');
assert(!html.includes('data-v12-mode="template"'),'template is a writing helper, not a workflow stage');
assert.match(html,/id="actionBeforePhotos"[^>]*type="file"[^>]*multiple/,'photos must be selectable when creating a finding');
assert.match(html,/id="photoStage"[^>]*>[\s\S]*?value="before"[\s\S]*?value="after"/,'before and after must remain distinct');
assert.match(html,/id="actionUploadResult"/,'upload success/failure must be visible');
assert(workspace.includes("state.autoMode?'write':state.mode")&&workspace.includes("matching?'document':'write'"),'new week starts with writing, submitted week with document review');
assert(css.includes('v13-workflow')&&css.includes('v13-action-photo-field'),'V13 styles missing');
assert(server.includes("version:'26.0.0'")&&server.includes("ui:'responsive-layout-v26'"),'server must identify new deployment');
assert(html.includes('/workflow-v13.css?v='),'browser must load versioned CSS');
const source=html.slice(html.indexOf('async function saveAction(){'),html.indexOf('async function loadActions(){'));
const doneSource=html.slice(html.indexOf('async function done(id){'),html.indexOf('async function loadAdmin(){'));
new vm.Script('('+source.trim()+')');
new vm.Script('('+doneSource.trim()+')');
const inputs={issueText:{value:'추락 위험 구간'},ai:{value:'난간 설치'},am:{value:'협력업체 담당자'},ad:{value:'2026-11-20'},ar:{value:''},actionContractor:{value:'7'},actionBeforePhotos:{files:[{type:'image/png',size:4096}],value:'before.png'},actionUploadResult:{textContent:'',classList:{toggle(){}},appendChild(x){this.retry=x}},photoStage:{value:'before'},photoTitle:{textContent:''}};
const calls=[];let photoResult='사진 1장 첨부 완료';
const sandbox={sid:12,document:{createElement(){return {}}},$:(id)=>{assert(inputs[id],`missing mock ${id}`);return inputs[id]},api:async(path,opts)=>{calls.push({path,opts});return path==='/api/actions'?{id:321}:{}},uploadPhotos:async(...args)=>{calls.push({upload:args});return photoResult},loadActions:async()=>{},loadDash:()=>{},toast:()=>{},openPhotos:async(...args)=>{calls.push({openPhotos:args})}};
const save=vm.runInNewContext('('+source.trim()+')',sandbox);
await save();
assert.equal(calls.filter(x=>x.path==='/api/actions').length,1,'one finding must be created');
assert.equal(calls.filter(x=>x.upload).length,1,'photo must be uploaded immediately after creation');
assert.equal(calls.find(x=>x.upload).upload[0],'action');
assert.equal(calls.find(x=>x.upload).upload[1],321);
assert.equal(calls.find(x=>x.upload).upload[3],'before');
assert.equal(inputs.issueText.value,'','successful registration should clear form');
assert.match(inputs.actionUploadResult.textContent,/등록 완료/);
inputs.issueText.value='새 지적';inputs.actionBeforePhotos.files=[{type:'image/png',size:4096}];photoResult='사진 첨부 실패: R2 연결 오류 (기록은 저장됨)';
await save();
assert.match(inputs.actionUploadResult.textContent,/등록되었습니다/,'partial success must not be reported as full success');
